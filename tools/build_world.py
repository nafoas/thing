def gen_focus():
    blocks = []
    for fid, icon, x, y, prereq, mutex, reward, filt in FOCUSES:
        b = [f"id = {fid}", f"icon = {icon}", f"x = {x}", f"y = {y}", "cost = 10"]
        for group in prereq:
            b.append("prerequisite = { " + " ".join(f"focus = {p}" for p in group) + " }")
        if mutex:
            b.append("mutually_exclusive = { " + " ".join(f"focus = {p}" for p in mutex) + " }")
        b.append(f"search_filters = {{ {filt} }}")
        b.append("ai_will_do = { factor = 1 }")
        b.append("completion_reward = {\n" + ind(reward) + "\n}")
        blocks.append(ind("focus = {\n" + ind("\n".join(b)) + "\n}"))
    tree = ("# Generated by tools/build_world.py\n"
            "# Shared focus tree for every nation of the reworked world except Rome and Eranshahr,\n"
            "# replacing vanilla trees whose history no longer exists.\n"
            "focus_tree = {\n\tid = aw_world_focus\n\tcountry = {\n\t\tfactor = 0\n"
            "\t\tmodifier = { add = 200 NOT = { tag = TUR tag = PER } }\n\t}\n\tdefault = no\n"
            "\tcontinuous_focus_position = { x = 50 y = 1100 }\n\n" + "\n\n".join(blocks) + "\n}\n")
    open(path("common", "national_focus", "aw_world_focus.txt"), "w", encoding="utf8").write(tree)


