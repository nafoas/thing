def path(*p):
    full = os.path.join(ROOT, *p)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    return full


def cos(c):
    return c["code"] if c["custom"] else "AW_" + c["code"]


def ind(s, n=1):
    return textwrap.indent(s, "\t" * n)


def loc_escape(s):
    return s.replace('"', "'").replace("\n", "\\n")


