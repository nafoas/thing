        pic, mods = THEMES[theme]
        out.append(f"\t\taw_{c['code']}_spirit = {{")
        out.append(f"\t\t\tpicture = {pic}")
        out.append("\t\t\tallowed = { always = no }")
        out.append("\t\t\tremoval_cost = -1")
