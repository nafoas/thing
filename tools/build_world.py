# Validation
# --------------------------------------------------------------------------
def validate():
    seen = collections.Counter(s for c in WORLD for s in c["states"])
    errors = []
    errors += [f"state {s} assigned {n} times" for s, n in seen.items() if n > 1]
    errors += [f"state {s} ({VANILLA[s]['name']}) unassigned" for s in VANILLA if s not in seen]
    errors += [f"state {s} does not exist" for s in seen if s not in VANILLA]
    errors += [f"{c['tag']} capital {c['capital']} not in its states" for c in WORLD if c["capital"] not in c["states"]]
    for key in ("tag", "code"):
        dup = [k for k, n in collections.Counter(c[key] for c in WORLD).items() if n > 1]
        errors += [f"duplicate {key} {d}" for d in dup]
    if errors:
        sys.exit("World data invalid:\n  " + "\n  ".join(errors))
    print(f"validated: {len(WORLD)} countries, {len(seen)} states")


